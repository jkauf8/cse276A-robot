"""Plan the HW4 paths and write what the robot needs.

    python3 -m hw4_planning.export      # from robot_control/: write config/hw4_fast.txt, hw4_safe.txt, hw4_localization.yaml
"""
import math
import os

from hw2_localization.ekf import wrap
from hw3_slam.paths import write as write_waypoints
from hw4_planning.safest import plan_safest
from hw4_planning.shortest import plan_shortest
from hw4_planning.world import clearance, load_world

ROBOT_RADIUS = 0.1115  # half-diagonal of the 16.5 x 15 cm robot
MARGIN = 0.05  # extra clearance for the fast planner only
PREFER = 'right'

# these repeat robot_control/velocity_control.py, which imports rclpy and so cannot be imported on a laptop
CRUISE_SPEED = 0.55
TURN_RATE = 3.49
PAUSE = 1.0

# loose gate: the tag map is known and the start pose is set by hand, so a tight gate locks every detection out
EKF_GATE = 1000.0

CONFIG = os.path.join(os.path.dirname(__file__), '..', 'config')


def plan_both(world, prefer=PREFER):
    return {'fast': plan_shortest(world, ROBOT_RADIUS + MARGIN, prefer),
            'safe': plan_safest(world, ROBOT_RADIUS, prefer=prefer)}


def to_start_frame(world, p):
    c, s = math.cos(world.start_heading), math.sin(world.start_heading)
    dx, dy = p[0] - world.start[0], p[1] - world.start[1]
    return (c * dx + s * dy, -s * dx + c * dy)


def from_start_frame(world, p):
    c, s = math.cos(world.start_heading), math.sin(world.start_heading)
    return (world.start[0] + c * p[0] - s * p[1], world.start[1] + s * p[0] + c * p[1])


def waypoints(world, path):
    pts = [to_start_frame(world, p) for p in path]
    thetas = [math.atan2(b[1] - a[1], b[0] - a[0]) for a, b in zip(pts, pts[1:])]
    thetas.append(thetas[-1])
    return [(x, y, th) for (x, y), th in zip(pts, thetas)]


def estimate_time(wps):
    t, x, y, theta = 0.0, 0.0, 0.0, 0.0

    def turn(target):
        angle = abs(wrap(target - theta))
        return (angle / TURN_RATE + PAUSE, target) if angle > 0.02 else (0.0, theta)

    for gx, gy, gtheta in wps:
        dt, theta = turn(math.atan2(gy - y, gx - x))
        t += dt + math.hypot(gx - x, gy - y) / CRUISE_SPEED + PAUSE
        x, y = gx, gy
        dt, theta = turn(gtheta)
        t += dt
    return t


def path_length(path):
    return sum(math.dist(a, b) for a, b in zip(path, path[1:]))


def min_clearance(world, path, step=0.01):
    best = math.inf
    for a, b in zip(path, path[1:]):
        n = max(1, math.ceil(math.dist(a, b) / step))
        for k in range(n + 1):
            t = k / n
            best = min(best, clearance(world, (a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1]))))
    return best


def _wall_normal(world, p):
    # direction (floor frame) pointing away from the nearest wall
    d = [(p[0], 0.0), (p[1], math.pi / 2), (world.arena - p[0], math.pi), (world.arena - p[1], -math.pi / 2)]
    return min(d)[1]


def write_localization_yaml(path, world):
    ids = sorted(world.landmarks)
    pos = [to_start_frame(world, world.landmarks[i]) for i in ids]
    yaw = [wrap(_wall_normal(world, world.landmarks[i]) - world.start_heading) for i in ids]

    def row(vals):
        return '[' + ', '.join(f'{v:.4f}' for v in vals) + ']'

    with open(path, 'w') as f:
        f.write('# Settings for localization_control on the HW4 run (generated by hw4_planning.export).\n')
        f.write('# Tag positions are in the start frame: origin = where the robot starts, x = its facing, y = left.\n')
        f.write(f"""/**:
  ros__parameters:
    tags:
      ids: [{', '.join(map(str, ids))}]
      x: {row(p[0] for p in pos)}
      y: {row(p[1] for p in pos)}
      z: {row([0.12] * len(ids))}
      yaw: {row(yaw)}
    camera:
      x: 0.01
      y: 0.0
      z: 0.125
      pitch_deg: 0.0
    ekf:
      gate: {EKF_GATE}
    camera_frame: camera_frame
    tag_frame_prefix: tag_
    waypoints_file: ''
    max_blind_time: 30.0
    start_delay: 1.0
    rate: 20.0
    min_cmd: 0.30
    deadband: 0.10
    min_turn_cmd: 0.38
    turn_tol_deg: 5.0
    reaim_tol_deg: 12.0
    pos_tol: 0.03
    final_checks: 2
    log_dir: /home/ubuntu/hw4_logs
""")


def main():
    world = load_world(os.path.join(CONFIG, 'hw4_world.yaml'))
    for name, path in plan_both(world).items():
        wps = waypoints(world, path)
        write_waypoints(os.path.join(CONFIG, f'hw4_{name}.txt'), wps)
        print(f'{name}: waypoints (floor frame) ' + ' '.join(f'({x:.3f}, {y:.3f})' for x, y in path))
        print(f'  length {path_length(path):.3f} m, min clearance {min_clearance(world, path):.3f} m, '
              f'estimated time {estimate_time(wps):.1f} s')
    write_localization_yaml(os.path.join(CONFIG, 'hw4_localization.yaml'), world)


if __name__ == '__main__':
    main()
